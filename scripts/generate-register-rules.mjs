#!/usr/bin/env node
// Identity comes from the data catalog; country fields come from the generated
// LML class description. No register-to-country inference or fallback default.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { parse } from 'yaml';

const catalogPath = process.argv[2] ?? 'data-ob/catalogs/registers.yaml';
const descriptionPath = 'src/lib/form/class-description.generated.json';
const catalog = readFileSync(catalogPath, 'utf8');
const descriptionText = readFileSync(descriptionPath, 'utf8');
const { registers } = parse(catalog);
const { classes } = JSON.parse(descriptionText);
const identities = {};
for (const register of registers) {
  if (identities[register.register_id]) throw new Error(`Duplicate register ${register.register_id}`);
  const fields = value => Array.isArray(value) ? value : [value];
  const keyFields = fields(register.key_field);
  if (!keyFields.length || keyFields.some(field => typeof field !== 'string' || !field)) throw new Error(`Missing identity for ${register.register_id}`);
  const amendmentClass = register.parser_class?.split('::').at(-1) ?? null;
  if (amendmentClass && !classes[amendmentClass]) throw new Error(`Unknown model ${amendmentClass}`);
  identities[register.register_id] = { keyFields, fallbackKeyFields: (register.fallback_key_fields ?? []).map(fields), amendmentClass };
}
const countries = {};
const entryFields = {};
for (const [name, cls] of Object.entries(classes)) {
  if (!name.endsWith('Amendment')) continue;
  const entries = cls.attributes.find(attribute => attribute.wire === 'entries' && attribute.collection);
  const fields = classes[entries?.type]?.attributes ?? [];
  entryFields[name] = fields.map(attribute => attribute.wire);
  const countryFields = fields.filter(attribute => ['country_or_area', 'country'].includes(attribute.wire) && ['String', 'MultilingualString'].includes(attribute.type));
  if (countryFields.length > 1) throw new Error(`Ambiguous country fields in ${name}`);
  countries[name] = countryFields[0]?.wire ?? null;
}
const hash = text => createHash('sha256').update(text).digest('hex');
const output = `// GENERATED by scripts/generate-register-rules.mjs — do not edit.\n// Catalog SHA256: ${hash(catalog)}\n// LML description SHA256: ${hash(descriptionText)}\n\nexport interface RegisterIdentity {\n  keyFields: readonly string[];\n  fallbackKeyFields: readonly (readonly string[])[];\n  amendmentClass: string | null;\n}\nexport const REGISTER_IDENTITIES: Readonly<Record<string, RegisterIdentity>> = ${JSON.stringify(identities, null, 2)};\n\nexport const AMENDMENT_COUNTRY_FIELDS: Readonly<Record<string, string | null>> = ${JSON.stringify(countries, null, 2)};\n\nexport const AMENDMENT_ENTRY_FIELDS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(entryFields, null, 2)};\n`;
writeFileSync('src/lib/register-rules.generated.ts', output);
console.log(`Generated register identity and country rules (${Object.keys(identities).length} registers)`);
