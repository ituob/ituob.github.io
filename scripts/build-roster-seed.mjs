#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const root = fileURLToPath(new URL("../", import.meta.url));
export const countrySource = "datasets/country-names/data.yaml";
const quote = (value) => `'${value.replaceAll("'", "''")}'`;

/** Bootstrap only: source countries are not proof of active TSB membership. */
export function buildRosterSeed(dataObRoot = resolve(root, "data-ob")) {
  const countries = parse(readFileSync(resolve(dataObRoot, countrySource), "utf8"));
  if (!Array.isArray(countries) || countries.length === 0) throw new Error("country roster must be a non-empty array");
  const ids = new Set(), names = new Set();
  const records = countries.map((country) => {
    const id = country?.key, name = country?.name?.en?.trim();
    if (typeof id !== "string" || !/^[a-z0-9-]+$/.test(id) || !name) throw new Error("invalid country key or English name");
    if (ids.has(id) || names.has(name)) throw new Error(`duplicate country key or register name: ${id}`);
    ids.add(id); names.add(name);
    return { id, name, register_key: name, status: "suspended" };
  }).sort((a, b) => a.id < b.id ? -1 : a.id > b.id ? 1 : 0);
  const sql = [
    "-- Generated by scripts/build-roster-seed.mjs; do not edit.",
    `-- Source: data-ob/${countrySource} at the git-pinned submodule revision.`,
    "-- Countries/areas are unverified: suspended until explicit admin activation.",
    "-- Bootstrap only; existing rows, statuses, timestamps and history are preserved.",
    ...records.map((r) => `INSERT INTO members (id, name, register_key, status, created_at, updated_at) VALUES (${quote(r.id)}, ${quote(r.name)}, ${quote(r.register_key)}, 'suspended', '1970-01-01T00:00:00.000Z', '1970-01-01T00:00:00.000Z') ON CONFLICT(id) DO NOTHING;`),
    "",
  ].join("\n");
  return { sql, records };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.length !== 2) throw new Error("usage: node scripts/build-roster-seed.mjs");
  const { sql, records } = buildRosterSeed();
  writeFileSync(resolve(root, "seeds/roster.sql"), sql);
  console.log(`Generated seeds/roster.sql: ${records.length} members; no identity or role grants`);
}
