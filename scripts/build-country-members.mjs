import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";
import { countryData, countryLabels } from "./country-data.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
export const normalizeCountry = value => value.normalize("NFKC").trim().toLowerCase().replace(/\s+/gu, " ");

/** Build-time reconciliation only. Runtime never guesses an administration from a partial name. */
export function buildCountryMembers(dataRoot = resolve(root, "data-ob")) {
  const read = path => parse(readFileSync(resolve(dataRoot, path), "utf8"));
  const countries = read("datasets/country-names/data.yaml");
  const aliases = JSON.parse(readFileSync(resolve(root, "scripts/country-member-aliases.json"), "utf8"));
  const members = new Set(countries.map(c => c.key));
  const mapping = new Map();
  const add = (label, id) => {
    const key = normalizeCountry(label);
    if (!key || !members.has(id)) throw new Error(`Invalid country alias ${label}: ${id}`);
    const previous = mapping.get(key);
    if (previous && previous !== id) throw new Error(`Ambiguous country ${label}: ${previous}, ${id}`);
    mapping.set(key, id);
  };
  for (const country of countries) {
    add(country.key, country.key);
    add(country.key.replaceAll("-", " "), country.key);
    for (const name of countryLabels(country.name)) {
      add(name, country.key);
      const short = name.split(" (")[0].trim();
      if (short) add(short, country.key);
    }
  }
  for (const [label, id] of Object.entries(aliases)) add(label, id);
  for (const country of read("datasets/iso-3166/data.yaml")) {
    const names = countryLabels(country.name);
    const ids = new Set(names.map(name => mapping.get(normalizeCountry(name))).filter(Boolean));
    if (ids.size > 1) throw new Error(`Ambiguous ISO country ${country.code}`);
    if (ids.size === 1) {
      const [id] = ids;
      add(country.code, id);
      add(`iso-3166:${country.code}`, id);
      for (const name of names) add(name, id);
    }
  }
  // Propagate reconciled row identities to every language and ISO alpha-3 code.
  // Collect candidates first so conflicting multilingual labels cannot depend on row order.
  const candidates = new Map([...mapping].map(([label, id]) => [label, new Set([id])]));
  for (const dataset of countryData(dataRoot)) for (const row of dataset.rows) for (const field of dataset.fields) {
    const value = row[field];
    const primary = typeof value === "string" ? value : value?.en;
    const id = primary ? mapping.get(normalizeCountry(primary)) : null;
    if (!id) continue;
    for (const label of [...countryLabels(value), ...(typeof row.iso_code === "string" ? [row.iso_code] : [])]) {
      const key = normalizeCountry(label);
      if (!key) continue;
      if (!candidates.has(key)) candidates.set(key, new Set());
      candidates.get(key).add(id);
    }
  }
  const conflicts = JSON.parse(readFileSync(resolve(root, "scripts/country-member-conflicts.json"), "utf8"));
  const used = new Set();
  for (const [label, ids] of candidates) {
    const resolution = conflicts[label];
    if (ids.size !== 1 || resolution) {
      if (!resolution?.reason || (resolution.member !== null && !ids.has(resolution.member))) throw new Error(`Ambiguous country ${label}: ${[...ids].join(", ")}`);
      used.add(label);
      if (resolution.member === null) mapping.delete(label);
      else mapping.set(label, resolution.member);
      continue;
    }
    mapping.set(label, [...ids][0]);
  }
  if (Object.keys(conflicts).some(label => !used.has(label))) throw new Error("Stale country conflict resolution");
  return Object.fromEntries([...mapping].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0));
}
export function countryMembersSource(mapping) {
  return `// Generated by scripts/build-country-members.mjs; do not edit.\n// Stable member IDs; no activation, identity or role grants.\nexport const COUNTRY_MEMBERS: Readonly<Record<string, string>> = ${JSON.stringify(mapping, null, 2)};\n`;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(resolve(root, "worker/lib/country-members.generated.ts"), countryMembersSource(buildCountryMembers()));
}
